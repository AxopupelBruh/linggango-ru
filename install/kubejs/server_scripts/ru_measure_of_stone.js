const NbtList = Java.loadClass('net.minecraft.nbt.ListTag')
const NbtString = Java.loadClass('net.minecraft.nbt.StringTag')
const Component = Java.loadClass('net.minecraft.network.chat.Component')

function applyRu(stack) {
  try {
    var tag = stack.getOrCreateTag()
    var pages = tag.getList('pages', 8) // 8 = StringTag
    if (pages.size() !== PAGE_RU.length) return
    // уже переведено?
    if (pages.getString(0).indexOf('День 3') === 0) return

    var list = new NbtList()
    for (var i = 0; i < PAGE_RU.length; i++) {
      list.add(NbtString.valueOf(
        Component.Serializer.toJson(Component.literal(PAGE_RU[i]))
      ))
    }
    tag.put('pages', list)
    // автор и название тоже английские
    tag.putString('author', 'Геомант')
    tag.putString('title', 'Мера камня')
  } catch (e) {
    console.error('[RU-BOOK] measure_of_stone: ' + e)
  }
}

PlayerEvents.inventoryChanged(event => {
  try {
    var stack = event.item
    if (!stack || stack.isEmpty()) return
    if (String(stack.id) !== BOOK_ID) return
    applyRu(stack)
  } catch (e) {
    console.error('[RU-BOOK] ' + e)
  }
})

// книга может прийти не через инвентарь (сундук, лут) — ловим при клике
ItemEvents.rightClicked(BOOK_ID, event => {
  applyRu(event.item)
})
